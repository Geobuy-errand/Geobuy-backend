// ============================================================
// Paystack webhook — POST /api/webhooks/paystack
// Set this URL in Paystack Dashboard → Settings → API Keys & Webhooks.
// Every event is verified with the x-paystack-signature header.
// ============================================================

const Payment = require('../models/Payment.model');
const Subscription = require('../models/Subscription.model');
const User = require('../models/User.model');
const paystack = require('../services/payments/paystack');
const createNotification = require('../utils/create-notification');
const { fromMinorUnits } = require('../utils/money');

const paymentController = () => require('./payment.controller');
const subscriptionController = () => require('./subscription.controller');
const walletController = () => require('./wallet.controller');

exports.handleWebhook = async (req, res) => {
  const raw = Buffer.isBuffer(req.body) ? req.body : Buffer.from(JSON.stringify(req.body || {}));

  if (!paystack.verifyWebhookSignature(raw, req.headers['x-paystack-signature'])) {
    console.warn('Paystack webhook: invalid signature');
    return res.status(401).send('Invalid signature');
  }

  let event;
  try {
    event = JSON.parse(raw.toString('utf8'));
  } catch (e) {
    return res.status(400).send('Invalid JSON');
  }

  // Acknowledge immediately; Paystack retries if we take too long.
  res.status(200).json({ received: true });

  try {
    await handleEvent(event, req.app.get('io'));
  } catch (err) {
    console.error(`Paystack webhook ${event?.event} failed:`, err);
  }
};

async function handleEvent(event, io) {
  const data = event.data || {};
  console.log('📦 Paystack webhook:', event.event, data.reference || data.subscription_code || '');

  switch (event.event) {
    case 'charge.success':
      return onChargeSuccess(data, io);

    case 'subscription.create':
      return subscriptionController().onPaystackSubscriptionCreated(data);

    case 'subscription.not_renew':
    case 'subscription.disable':
      return onSubscriptionStopped(data, event.event);

    case 'invoice.payment_failed':
      return onInvoiceFailed(data);

    case 'transfer.success':
      return walletController().completeWithdrawalByReference(data.reference, data);

    case 'transfer.failed':
    case 'transfer.reversed':
      return walletController().failWithdrawalByReference(data.reference, data.reason || event.event);

    case 'refund.processed':
      return onRefundProcessed(data);

    default:
      return null;
  }
}

async function onChargeSuccess(data, io) {
  const metadata = typeof data.metadata === 'string' ? safeJson(data.metadata) : data.metadata || {};
  const payment = await Payment.findOne({ reference: data.reference });

  if (payment) {
    if (payment.type === 'subscription') {
      return subscriptionController().activatePaystackSubscriptionFromPayment(payment, data);
    }
    return paymentController().applyVerifiedPayment(
      payment,
      {
        paid: data.status === 'success',
        amount: fromMinorUnits(data.amount, data.currency),
        currency: data.currency,
        reference: data.reference,
        metadata,
      },
      io
    );
  }

  // Renewal charge for an existing Paystack subscription (reference generated by Paystack)
  const planCode = data.plan?.plan_code || (typeof data.plan === 'string' ? data.plan : null);
  if (planCode) return subscriptionController().onPaystackRenewal(data);

  console.log('Paystack charge.success with unknown reference:', data.reference);
  return null;
}

async function onSubscriptionStopped(data, eventName) {
  const sub = await Subscription.findOne({ paystackSubscriptionCode: data.subscription_code });
  if (!sub) return;
  if (eventName === 'subscription.disable') {
    sub.status = 'canceled';
    sub.canceledAt = new Date();
    await User.findByIdAndUpdate(sub.userId, {
      'subscription.isSubscribed': false,
      'subscription.subscriptionStatus': 'canceled',
    });
    await createNotification(sub.userId, 'subscription_canceled', 'Subscription ended', 'Your subscription has ended.', {
      subscriptionId: sub._id,
    });
  } else {
    sub.cancelAtPeriodEnd = true;
  }
  await sub.save();
}

async function onInvoiceFailed(data) {
  const code = data.subscription?.subscription_code;
  const sub = code ? await Subscription.findOne({ paystackSubscriptionCode: code }) : null;
  if (!sub) return;
  sub.status = 'past_due';
  await sub.save();
  await User.findByIdAndUpdate(sub.userId, { 'subscription.subscriptionStatus': 'past_due' });
  await createNotification(
    sub.userId,
    'payment_failed',
    'Subscription payment failed',
    "We couldn't charge your card for your subscription. Please update your card.",
    { subscriptionId: sub._id }
  );
}

async function onRefundProcessed(data) {
  const reference = data.transaction_reference || data.transaction?.reference;
  if (!reference) return;
  await Payment.updateOne(
    { reference, status: { $in: ['succeeded', 'refund_pending', 'refunded'] } },
    { $set: { status: 'refunded', refundedAt: new Date() } }
  );
}

function safeJson(s) {
  try {
    return JSON.parse(s);
  } catch (e) {
    return {};
  }
}
